#!/usr/bin/env bash
# Writes libhegel/stub-generated.c from libhegel/hegel.h: a definition of
# every libhegel function that returns a `hegel_result_t`, failing with
# HEGEL_E_BACKEND. With libhegel/stub.c, which defines the rest by hand, it
# is the engine the `CHegel` target links on platforms libhegel has no build
# for.
#
# Scripts/package-libhegel.sh runs this after it copies a release's header,
# so the stub follows every libhegel bump. It fails when the header declares
# a function that returns something else and stub.c doesn't define it.
#
# Usage: Scripts/generate-engine-stub.sh

set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
dir="$root/libhegel"
tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

# cbindgen writes each declaration starting in column 0 with its return
# type, and ending with `);`. Struct fields and enum cases are indented, and
# function pointer types start with `typedef`.
awk -v manual="$dir/stub.c" '
    function name_of(line) {
        match(line, /hegel_[a-z0-9_]+\(/)
        return substr(line, RSTART, RLENGTH - 1)
    }
    BEGIN {
        while ((getline line < manual) > 0) {
            if (line ~ /^[a-z_][a-z0-9_ ]*[ *]hegel_[a-z0-9_]+\(/) {
                defined[name_of(line)] = 1
            }
        }
        print "// Generated by Scripts/generate-engine-stub.sh from hegel.h; do not edit."
        print "// See stub.c."
        print ""
        print "#include \"hegel.h\""
        print ""
        print "#pragma GCC diagnostic ignored \"-Wunused-parameter\""
    }
    !inside && /^[a-z_][a-z0-9_ ]*[ *]hegel_[a-z0-9_]+\(/ && !/^typedef/ {
        inside = 1
        declaration = ""
        name = name_of($0)
        type = substr($0, 1, index($0, name) - 1)
        sub(/ +$/, "", type)
    }
    inside {
        declaration = declaration $0 "\n"
        if ($0 !~ /\);[ \t]*$/) {
            next
        }
        inside = 0
        if (name in defined) {
            next
        }
        if (type != "hegel_result_t") {
            printf "error: %s returns %s; define it in libhegel/stub.c\n", name, type > "/dev/stderr"
            failed = 1
            next
        }
        sub(/;[ \t]*\n$/, "", declaration)
        printf "\n%s {\n    return HEGEL_E_BACKEND;\n}\n", declaration
        count++
    }
    END {
        if (failed) {
            exit 1
        }
        if (count == 0) {
            print "error: no declarations found in hegel.h" > "/dev/stderr"
            exit 1
        }
    }
' "$dir/hegel.h" > "$tmp"

mv "$tmp" "$dir/stub-generated.c"
trap - EXIT
